"""AIL.5C Grader golden-set release gate (design section I, "Release gate").

    Before a Grader version or model policy becomes ACTIVE, an offline golden-set
    run confirms expected findings on authored responses per definition
    (2 clear pass, 2 clear fail, 2 borderline). This is a test and script gate,
    not a schema.

The gate runs a *candidate* Grader configuration (an Agent Version's prompt and
model policy, or a pinned provider model) through the real machinery: the
allowlisted ``GradingPacketBuilder``, the ``Academy Grader`` with its
``grading_contract_v1`` parsing and its cross-check. It only replaces the
learner: each golden response is frozen into a synthetic attempt of the real
definition, with the deterministic stage assumed met, so that what is measured
is the Grader's judgment and nothing else. It writes no evidence and derives no
state, and it must only ever be run against a disposable database (the CLI
enforces that by working on a copy).

A candidate is **release-ready** only if every case of every approved
definition matches its expectation and every approved definition is covered.
Anything less is *not ready*; there is no partial pass.

Golden cases are authored per definition. Where none are authored, they are
derived deterministically from the definition's own authored reference points
(never generated by a model), and marked ``derived_from_reference_points``.
"""

